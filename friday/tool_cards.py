"""
Tool cards: what the retriever indexes and what a stage-2 chooser reads.

A card says what a tool does and does not do, the words people use for it,
a phrasing or two, and which sibling it is mistaken for. Cards are written
from each tool's registered behaviour. They are never copied from a benchmark
request: a card that echoes the test set makes the benchmark meaningless.

`index_text(name)` is the retriever's document: what the tool does, its aliases
and examples. `does_not` and `confusable_with` stay out of it on purpose - they
carry the words of the *wrong* tool - and appear only in `compact(name)`, the
line a chooser sees.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Card:
    domain: str
    does: str
    aliases: tuple[str, ...] = ()
    examples: tuple[str, ...] = ()
    does_not: str = ""
    confusable_with: tuple[str, ...] = ()


def _c(domain, does, aliases="", examples="", does_not="", confusable=""):
    """Authoring shorthand: aliases and confusable are space/comma lists, examples are `|`."""
    return Card(domain, does,
                tuple(a.strip() for a in aliases.split(",") if a.strip()),
                tuple(e.strip() for e in examples.split("|") if e.strip()),
                does_not,
                tuple(c for c in confusable.split() if c))


