def card(name: str) -> Card | None:
    return CARDS.get(name)


def index_text(name: str) -> str:
    """What the retriever indexes for a tool: its work, its aliases, its examples."""
    c = CARDS.get(name)
    if c is None:
        return ""
    return " ".join([c.does, " ".join(c.aliases), " ".join(c.examples), c.domain])


def compact(name: str, description: str = "") -> str:
    """One line for a stage-2 chooser: name, what it does and does not do, who it is confused with."""
    c = CARDS.get(name)
    if c is None:
        return f"{name}: {' '.join(description.split())[:120]}"
    line = f"{name}: {c.does}"
    if c.does_not:
        line += f"; not: {c.does_not}"
    if c.confusable_with:
        line += f" [vs {', '.join(c.confusable_with)}]"
    return line
