"""
One source harness, two tools (HARN-001).

FRIDAY's engineering harness - the rules, the `friday-*` roles, the skills and
the hooks - is written once, under the repo's `.claude/`. This module renders
it into the two layouts that consume it, so a change to the source reaches
both from one regeneration and the two never drift:

    Claude Code layout   rules/ agents/ skills/ hooks/   (the source, verbatim)
    Hermes profile       SOUL.md (managed block), skills/friday-harness/...,
                         agent-hooks/, harness.config.yaml (merge fragment)

How each part lands in Hermes (read from its install, not guessed):

    rules   - the compact rule set and every `alwaysApply` rule go into the
              managed block of the profile's SOUL.md (Hermes loads SOUL.md
              into the system prompt); every rule is also a loadable skill
              `friday-rule-<stem>` for the path-scoped ones.
    roles   - Claude Code subagents have no Hermes twin; each becomes a skill
              `friday-role-<name>` with the tool names translated to Hermes'
              (`Bash` -> `terminal`), loaded or handed to `delegate_task`.
    skills  - copied as Hermes skills (description cut to Hermes' 60 chars).
    hooks   - `.claude/settings.json` hooks that run a script of ours become
              Hermes shell hooks (`on_session_start`, `pre_tool_call`, ...).
    MCP     - an `mcp_servers.friday` entry points the profile at FRIDAY's
              MCP server.

The generator only writes into directories the caller names. It refuses the
live `.claude/` of the source repo, the owner's `~/.claude`, the Hermes install
and the Hermes home around it (its `profiles/`, `config.yaml`, `auth.json`,
`SOUL.md`), compared by resolved path so a junction or symlink cannot slip
past, unless the caller passes `allow_live=True`. The profile's `config.yaml`
is never edited: `harness.config.yaml` is a fragment to merge.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import urlparse

import yaml

DEFAULT_MCP_URL = "http://127.0.0.1:8000/sse"

BEGIN_MARK = "<!-- friday-harness:begin (generated by friday.harness_sync; edit .claude/, not this block) -->"
END_MARK = "<!-- friday-harness:end -->"
MANIFEST = ".harness-sync.json"
HOOK_BASH_ENV = "FRIDAY_HOOK_BASH"     # explicit override for the shell that runs hooks
CONTEXT_WRAPPER = "agent-hooks/.context-hook.sh"
MCP_TRANSPORTS = ("auto", "sse", "http")

COMPACT_RULE = "00-team-rules"
SKILL_GROUP = "friday-harness"
DESCRIPTION_LIMIT = 60          # Hermes skills/AGENTS.md authoring standard

# Claude Code tool name -> the Hermes tool that does the same job.
TOOL_MAP = {
    "Read": "read_file", "Glob": "search_files", "Grep": "search_files",
    "Bash": "terminal", "Edit": "patch", "Write": "write_file",
    "WebFetch": "web_extract", "WebSearch": "web_search",
}
# Claude Code hook event -> Hermes hook event (hermes_cli.plugins.VALID_HOOKS).
HOOK_EVENTS = {
    "SessionStart": "on_session_start",
    "PreToolUse": "pre_tool_call",
    "PostToolUse": "post_tool_call",
}

_FRONT = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n?(.*)\Z", re.DOTALL)
_SAFE_NAME = re.compile(r"\A[A-Za-z0-9][A-Za-z0-9._-]*\Z")


class HarnessSourceError(RuntimeError):
    """The source tree is not a harness (nothing to render, or unreadable)."""


class RefusedTarget(RuntimeError):
    """An output directory is a live location and `allow_live` was not given."""


@dataclass
class SyncResult:
    written: list[str] = field(default_factory=list)
    removed: list[str] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)   # source items with no Hermes twin
    unavailable: list[str] = field(default_factory=list)   # hooks not emitted, with the reason


@dataclass
class _Doc:
    stem: str
    raw: bytes
    meta: dict
    body: str


@dataclass
class _Source:
    rules: list[_Doc]
    agents: list[_Doc]
    skills: dict[str, dict[str, bytes]]      # skill dir -> {relative path: bytes}
    hooks: dict[str, bytes]
    settings_hooks: dict


# ---------------------------------------------------------------------------
# Reading the source
# ---------------------------------------------------------------------------

def _split(raw: bytes, where: str) -> tuple[dict, str]:
    text = raw.decode("utf-8").replace("\r\n", "\n")
    match = _FRONT.match(text)
    if not match:
        return {}, text
    try:
        meta = yaml.safe_load(match.group(1)) or {}
    except yaml.YAMLError as exc:
        raise HarnessSourceError(f"{where}: bad frontmatter: {exc}") from exc
    if not isinstance(meta, dict):
        raise HarnessSourceError(f"{where}: frontmatter is not a mapping")
    return meta, match.group(2)


def _docs(folder: Path) -> list[_Doc]:
    out = []
    for path in sorted(folder.glob("*.md")) if folder.is_dir() else []:
        if path.is_symlink() or not path.is_file():
            continue
        raw = path.read_bytes()
        meta, body = _split(raw, str(path))
        out.append(_Doc(path.stem, raw, meta, body))
    return out


def _load(source_root: Path) -> _Source:
    base = Path(source_root) / ".claude"
    if not base.is_dir():
        raise HarnessSourceError(f"no .claude/ under {source_root}")
    skills: dict[str, dict[str, bytes]] = {}
    for skill_md in sorted((base / "skills").glob("*/SKILL.md")):
        folder = skill_md.parent
        if not _SAFE_NAME.match(folder.name):
            raise HarnessSourceError(f"unsafe skill name: {folder.name!r}")
        skills[folder.name] = {
            p.relative_to(folder).as_posix(): p.read_bytes()
            for p in sorted(folder.rglob("*")) if p.is_file() and not p.is_symlink()}
    hooks = {p.name: p.read_bytes() for p in sorted((base / "hooks").glob("*"))
             if p.is_file() and not p.is_symlink()} if (base / "hooks").is_dir() else {}
    settings_hooks: dict = {}
    settings = base / "settings.json"
    if settings.is_file():
        try:
            settings_hooks = json.loads(settings.read_text(encoding="utf-8")).get("hooks") or {}
        except (ValueError, AttributeError) as exc:
            raise HarnessSourceError(f"{settings}: not valid settings JSON: {exc}") from exc
    src = _Source(_docs(base / "rules"), _docs(base / "agents"), skills, hooks, settings_hooks)
    if not (src.rules or src.agents or src.skills):
        raise HarnessSourceError(f"{base} holds no rules, agents or skills")
    return src


# ---------------------------------------------------------------------------
# Rendering the Hermes layout
# ---------------------------------------------------------------------------

def _short(text: object, fallback: str) -> str:
    """One sentence of at most DESCRIPTION_LIMIT chars ending in a period."""
    flat = " ".join(str(text or "").split()) or fallback
    first = re.split(r"(?<=[.!?])\s", flat, maxsplit=1)[0].rstrip(".!? ")
    if len(first) > DESCRIPTION_LIMIT - 1:
        first = first[:DESCRIPTION_LIMIT - 1]
        if " " in first:
            first = first.rsplit(" ", 1)[0]
        first = first.rstrip(" ,;:-")
    return first + "."


def _heading(body: str, fallback: str) -> str:
    for line in body.splitlines():
        if line.startswith("#"):
            return line.lstrip("# ").strip()
    return fallback


def _skill_md(name: str, description: str, body: str) -> bytes:
    meta = {"name": name, "description": description, "version": "1.0.0",
            "author": "FRIDAY harness (generated)",
            "metadata": {"hermes": {"tags": [SKILL_GROUP], "category": SKILL_GROUP}}}
    front = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=1000)
    return f"---\n{front}---\n\n{body.strip()}\n".encode("utf-8")


def _tools(meta: dict) -> list[str]:
    raw = meta.get("tools") or []
    if isinstance(raw, str):
        raw = [t.strip() for t in raw.split(",")]
    mapped: list[str] = []
    for tool in raw:
        for name in re.split(r"\|", str(tool)):
            hermes = TOOL_MAP.get(name.strip(), name.strip())
            if hermes and hermes not in mapped:
                mapped.append(hermes)
    return mapped


def _role_name(doc: _Doc) -> str:
    return "friday-role-" + str(doc.meta.get("name") or doc.stem).removeprefix("friday-")


def _rule_name(doc: _Doc) -> str:
    return f"friday-rule-{doc.stem}"


def _rule_description(doc: _Doc) -> str:
    return _short(doc.meta.get("description"), _heading(doc.body, doc.stem))


def _paths(doc: _Doc) -> list[str]:
    raw = doc.meta.get("paths") or []
    return [raw] if isinstance(raw, str) else [str(p) for p in raw]


def _soul_block(src: _Source, mcp_url: str) -> str:
    compact = next((d for d in src.rules if d.stem == COMPACT_RULE), None)
    always = [d for d in src.rules
              if d.stem != COMPACT_RULE and d.meta.get("alwaysApply") is True]
    on_demand = [d for d in src.rules
                 if d.stem != COMPACT_RULE and d.meta.get("alwaysApply") is not True]
    lines = [BEGIN_MARK, "", "## FRIDAY engineering harness", "",
             "Generated from the repo's `.claude/` so Hermes and Claude Code follow the "
             "same plan-first, test-first and verification rules. Edit the source and run "
             "`scripts/harness_sync.py`; never edit this block.", ""]
    if compact:
        lines += [compact.body.strip(), ""]
    for doc in always:
        lines += [doc.body.strip(), ""]
    lines += ["### Rules to load before touching their paths",
              "The numbered rules are skills; load the matching one with `skill_view`.", ""]
    for doc in on_demand:
        scope = f" (paths: {', '.join(_paths(doc))})" if _paths(doc) else ""
        lines.append(f"- `{_rule_name(doc)}`: {_rule_description(doc)}{scope}")
    lines += ["", "### Roles",
              "Load a role with `skill_view`, or give it to `delegate_task`.", ""]
    for doc in src.agents:
        lines.append(f"- `{_role_name(doc)}`: {_short(doc.meta.get('description'), doc.stem)}")
    lines += ["", "### Skills", ""]
    for name, files in src.skills.items():
        meta, _ = _split(files["SKILL.md"], name)
        lines.append(f"- `{name}`: {_short(meta.get('description'), name)}")
    lines += ["", "### FRIDAY tools",
              f"FRIDAY's MCP tools come from the `friday` MCP server ({mcp_url}); "
              "see `harness.config.yaml` next to this profile.", "", END_MARK]
    return "\n".join(lines)


def _merge_soul(existing: str, block: str) -> str:
    start, end = existing.find(BEGIN_MARK), existing.find(END_MARK)
    if (existing.count(BEGIN_MARK), existing.count(END_MARK)) not in ((0, 0), (1, 1)) \
            or (start != -1 and end < start):
        raise HarnessSourceError(
            "SOUL.md holds unbalanced friday-harness markers; fix or remove them by hand "
            "(refusing to guess which text is generated)")
    if start != -1:
        return existing[:start] + block + existing[end + len(END_MARK):]
    if not existing.strip():
        return block + "\n"
    return existing.rstrip("\n") + "\n\n" + block + "\n"


# ---------------------------------------------------------------------------
# The POSIX shell that runs the hooks
# ---------------------------------------------------------------------------

def _on_windows() -> bool:
    return sys.platform == "win32"


def _is_wsl_launcher(path: str) -> bool:
    """True for the WSL `bash.exe` stub (WindowsApps alias or System32), which cannot see C:/ paths."""
    low = str(path).replace("\\", "/").lower()
    return "/windowsapps/" in low or low.endswith("/system32/bash.exe") or "/sysnative/bash.exe" in low


def _usable_bash(path: str) -> str | None:
    if not path or not os.path.isfile(path) or (_on_windows() and _is_wsl_launcher(path)):
        return None
    return Path(os.path.abspath(path)).as_posix()


def resolve_hook_bash(override: str | None = None) -> tuple[str | None, str]:
    """
    The absolute path of the bash that runs generated hooks, and a reason when none.

    Order: `override`, then $FRIDAY_HOOK_BASH, then on Windows the Git for Windows
    bash found from git's install (<Git>/bin or <Git>/usr/bin; never the WSL
    launcher in WindowsApps, which cannot see C:/ paths and would make every hook
    print nothing), then plain `bash` elsewhere. An explicit override that is not
    usable is an error, not a cue to fall back.
    """
    explicit = override or os.environ.get(HOOK_BASH_ENV, "").strip()
    if explicit:
        found = _usable_bash(explicit)
        if found:
            return found, ""
        source = "the hook_bash argument" if override else HOOK_BASH_ENV
        wsl = " (the WSL launcher cannot run hooks given Windows paths)" if _on_windows() and _is_wsl_launcher(explicit) else ""
        return None, f"hook shell {explicit!r} (from {source}) is not an existing bash{wsl}"
    if _on_windows():
        git = shutil.which("git")
        if git:
            here = Path(git).resolve().parent
            for root in (here.parent, here.parent.parent, here):       # <Git>/cmd, <Git>/mingw64/bin, <Git>/bin
                for rel in ("bin/bash.exe", "usr/bin/bash.exe"):
                    found = _usable_bash(str(root / rel))
                    if found:
                        return found, ""
        found = _usable_bash(shutil.which("bash") or "")
        if found:
            return found, ""
        return None, ("no Git for Windows bash found (git's install has no bin/bash.exe or usr/bin/bash.exe, and the "
                      f"only `bash` on PATH is the WSL launcher or absent); install Git for Windows or set {HOOK_BASH_ENV}")
    found = _usable_bash(shutil.which("bash") or "")
    return (found, "") if found else (None, f"no bash on PATH; set {HOOK_BASH_ENV}")


# Claude Code's SessionStart hooks print plain text that becomes context; Hermes
# only takes context from a JSON {"context": ...} on stdout. This wrapper runs
# the script (CLAUDE_PROJECT_DIR defaults to the source repo) and re-emits its
# output in that shape using only bash, tr and sed. A failing script is reported on
# stderr with a non-zero exit (Hermes warns and logs it; the session still starts).
_CONTEXT_WRAPPER = r"""#!/usr/bin/env bash
# Generated by friday.harness_sync: run a Claude Code SessionStart script and emit
# its stdout as the JSON {"context": ...} a Hermes shell hook expects.
export CLAUDE_PROJECT_DIR="${CLAUDE_PROJECT_DIR:-@PROJECT_DIR@}"
err=$(mktemp) || exit 1
trap 'rm -f "$err"' EXIT
out=$("${BASH:-bash}" "$1" 2>"$err")
rc=$?
if [ "$rc" -ne 0 ]; then
  # exit 1, never 2 (2 blocks a blocking-capable event): Hermes logs a non-zero
  # exit with this stderr, instead of a silent empty context.
  printf 'friday harness: session hook %s failed (exit %s): %s\n' "$1" "$rc" "$(head -c 400 "$err")" >&2
  exit 1
fi
body=$(printf '%s' "$out" | tr -d '\000-\010\013\014\016-\037' \
  | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/\t/\\t/g' \
  | sed -e ':a' -e 'N' -e '$!ba' -e 's/\n/\\n/g')
printf '{"context": "%s"}\n' "$body"
"""


def _q(path: str) -> str:
    return '"' + path + '"'


def _hook_entries(src: _Source, out_dir: str, result: SyncResult, bash: str | None, why: str = "") -> dict:
    agent_hooks = out_dir + "/agent-hooks"
    out: dict[str, list[dict]] = {}
    for event, groups in src.settings_hooks.items():
        target = HOOK_EVENTS.get(event)
        if target is None:
            result.skipped.append(f"hook event {event}")
            continue
        for group in groups if isinstance(groups, list) else []:
            matcher = group.get("matcher") if isinstance(group, dict) else None
            for hook in (group.get("hooks") if isinstance(group, dict) and "hooks" in group else [group]):
                command = str(hook.get("command", "")) if isinstance(hook, dict) else ""
                script = re.search(r"\.claude/hooks/([A-Za-z0-9._-]+)", command)
                if not script or script.group(1) not in src.hooks:
                    result.skipped.append(f"hook command {command!r}")
                    continue
                if bash is None:
                    result.unavailable.append(f"hook {event} {script.group(1)}: {why}")
                    continue
                path = _q(f"{agent_hooks}/{script.group(1)}")
                if target == "on_session_start":
                    entry: dict = {"command": f"{_q(bash)} {_q(out_dir + '/' + CONTEXT_WRAPPER)} {path}"}
                else:
                    entry = {"command": f"{_q(bash)} {path}"}
                if matcher:
                    entry = {"matcher": "|".join(TOOL_MAP.get(m, m) for m in str(matcher).split("|")),
                             **entry}
                out.setdefault(target, []).append(entry)
    return out


def _transport(url: str, transport: str) -> bool:
    """True when Hermes must be told `transport: sse` (it picks SSE from that key only)."""
    if transport not in MCP_TRANSPORTS:
        raise ValueError(f"mcp_transport must be one of {MCP_TRANSPORTS}, not {transport!r}")
    if transport == "auto":
        return urlparse(url).path.rstrip("/").endswith("/sse")
    return transport == "sse"


def _fragment(src: _Source, out_dir: str, mcp_url: str, mcp_transport: str,
              result: SyncResult, bash: str | None, why: str) -> bytes:
    server: dict = {"url": mcp_url}
    if _transport(mcp_url, mcp_transport):
        server["transport"] = "sse"
    server.update({"enabled": True, "timeout": 120, "connect_timeout": 30})
    config: dict = {
        "skills": {"external_dirs": [out_dir + "/skills"]},
        "mcp_servers": {"friday": server},
    }
    hooks = _hook_entries(src, out_dir, result, bash, why)
    if hooks:
        config["hooks"] = hooks
    head = ("# Generated by friday.harness_sync - merge these keys into the Hermes profile's\n"
            "# config.yaml (it is never edited for you). Hermes asks once before it runs a\n"
            "# shell hook; pass --accept-hooks or set hooks_auto_accept to skip the prompt.\n")
    return (head + yaml.safe_dump(config, sort_keys=False, allow_unicode=True)).encode("utf-8")


def _hermes_files(src: _Source, out_dir: str, project_dir: str, mcp_url: str,
                  mcp_transport: str, result: SyncResult, bash: str | None,
                  why: str = "") -> dict[str, bytes]:
    base = f"skills/{SKILL_GROUP}"
    files: dict[str, bytes] = {}
    for doc in src.rules:
        scope = _paths(doc)
        body = (f"Applies to: {', '.join(scope)}\n\n" if scope else "") + doc.body
        files[f"{base}/{_rule_name(doc)}/SKILL.md"] = _skill_md(
            _rule_name(doc), _rule_description(doc), body)
    for doc in src.agents:
        tools = _tools(doc.meta)
        head = [f"# Role: {doc.meta.get('name') or doc.stem}", ""]
        if doc.meta.get("description"):
            head += [str(doc.meta["description"]).strip(), ""]
        if tools or doc.meta.get("model"):
            head += [f"Hermes tools: {', '.join(tools) or 'as the task needs'}. "
                     f"Model hint: {doc.meta.get('model') or 'default'}.", ""]
        files[f"{base}/{_role_name(doc)}/SKILL.md"] = _skill_md(
            _role_name(doc), _short(doc.meta.get("description"), doc.stem),
            "\n".join(head) + "\n" + doc.body)
    for name, skill_files in src.skills.items():
        for rel, raw in skill_files.items():
            if rel == "SKILL.md":
                meta, body = _split(raw, name)
                full = " ".join(str(meta.get("description", "")).split())
                short = _short(full, name)
                lead = f"> {full}\n\n" if full and full != short else ""
                files[f"{base}/{name}/SKILL.md"] = _skill_md(name, short, lead + body)
            else:
                files[f"{base}/{name}/{rel}"] = raw
    for name, raw in src.hooks.items():
        files[f"agent-hooks/{name}"] = raw
    if "on_session_start" in _hook_entries(src, out_dir, SyncResult(), bash, why):
        files[CONTEXT_WRAPPER] = _CONTEXT_WRAPPER.replace("@PROJECT_DIR@", project_dir).encode("utf-8")
    files["harness.config.yaml"] = _fragment(src, out_dir, mcp_url, mcp_transport, result, bash, why)
    return files


def _claude_files(src: _Source) -> dict[str, bytes]:
    files = {f"rules/{d.stem}.md": d.raw for d in src.rules}
    files.update({f"agents/{d.stem}.md": d.raw for d in src.agents})
    for name, skill_files in src.skills.items():
        files.update({f"skills/{name}/{rel}": raw for rel, raw in skill_files.items()})
    files.update({f"hooks/{name}": raw for name, raw in src.hooks.items()})
    return files


# ---------------------------------------------------------------------------
# Writing, checking, refusing
# ---------------------------------------------------------------------------

def _inside(root: Path, rel: str) -> Path:
    """`root/rel`, or an error if `rel` (e.g. from a hand-edited manifest) escapes root."""
    target = Path(os.path.abspath(root / rel))
    top = Path(os.path.abspath(root))
    if target != top and top not in target.parents:
        raise HarnessSourceError(f"{rel!r} escapes {root}")
    return target


def _real(path) -> Path:
    """Resolved, case-normalised path: a junction or symlink cannot hide a live location."""
    return Path(os.path.normcase(os.path.realpath(path)))


def _protected(source_root: Path, hermes_root: Path | None, extra=()) -> list[Path]:
    paths = [Path(source_root) / ".claude", Path.home() / ".claude", Path.home() / ".hermes"]
    if hermes_root:
        paths.append(Path(hermes_root))
        home = Path(hermes_root).parent       # profiles/, config.yaml, auth.json, SOUL.md
        if home != home.parent:
            paths.append(home)
    paths.extend(Path(p) for p in extra)
    return [_real(p) for p in paths]


def _refuse_live(out: Path, protected: list[Path]) -> None:
    here = _real(out)
    for live in protected:
        if here == live or live in here.parents:
            raise RefusedTarget(
                f"{out} is a live location ({live}); pass allow_live=True to write there")


def _prior(out: Path) -> list[str]:
    path = out / MANIFEST
    if not path.is_file():
        return []
    try:
        return list(json.loads(path.read_text(encoding="utf-8")).get("files", []))
    except (ValueError, AttributeError) as exc:
        raise HarnessSourceError(f"{path}: unreadable manifest: {exc}") from exc


def _apply(out: Path, files: dict[str, bytes], label: str, result: SyncResult) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for rel, data in sorted(files.items()):
        target = _inside(out, rel)
        if not target.is_file() or target.read_bytes() != data:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            result.written.append(f"{label}:{rel}")
    for rel in _prior(out):
        if rel in files:
            continue
        target = _inside(out, rel)
        if target.is_file():
            target.unlink()
            result.removed.append(f"{label}:{rel}")
            for parent in target.parents:
                if parent == out or any(parent.iterdir()):
                    break
                parent.rmdir()
    manifest = json.dumps({"generator": "friday.harness_sync",
                           "files": sorted(files)}, indent=1).encode("utf-8")
    path = out / MANIFEST
    if not path.is_file() or path.read_bytes() != manifest:
        path.write_bytes(manifest)


def _soul_text(hermes_out: Path, block: str) -> bytes:
    soul = hermes_out / "SOUL.md"
    existing = soul.read_bytes().decode("utf-8") if soul.is_file() else ""
    return _merge_soul(existing, block).encode("utf-8")


def _expected(source_root: Path, hermes_out: Path, mcp_url: str, mcp_transport: str,
              result: SyncResult, hook_bash: str | None = None):
    src = _load(source_root)
    bash, why = resolve_hook_bash(hook_bash) if src.settings_hooks else (None, "")
    block = _soul_block(src, mcp_url)
    out_dir = Path(os.path.abspath(hermes_out)).as_posix()
    project = Path(os.path.abspath(source_root)).as_posix()
    return (_claude_files(src),
            _hermes_files(src, out_dir, project, mcp_url, mcp_transport, result, bash, why), block)


def render(source_root, claude_out, hermes_out, *, mcp_url: str = DEFAULT_MCP_URL,
           mcp_transport: str = "auto", hermes_root=None, protect=(),
           allow_live: bool = False, hook_bash: str | None = None) -> SyncResult:
    """
    Regenerate both layouts from `<source_root>/.claude`. Only the two named
    directories are written. `hermes_root` is the Hermes install (so it, and the
    Hermes home around it, can be refused); pass
    `friday.hermes_bridge.locate()["root"]`. `protect` names more live paths.
    `hook_bash` overrides the shell that runs hooks (see `resolve_hook_bash`); when none
    is usable no hook is emitted and `SyncResult.unavailable` says why.
    """
    source_root, claude_out, hermes_out = Path(source_root), Path(claude_out), Path(hermes_out)
    result = SyncResult()
    claude, hermes, block = _expected(source_root, hermes_out, mcp_url, mcp_transport, result, hook_bash)
    if not allow_live:
        protected = _protected(source_root, Path(hermes_root) if hermes_root else None, protect)
        _refuse_live(claude_out, protected)
        _refuse_live(hermes_out, protected)
    soul = _soul_text(hermes_out, block)
    _apply(claude_out, claude, "claude", result)
    _apply(hermes_out, {**hermes, "SOUL.md": soul}, "hermes", result)
    return result


def check(source_root, claude_out, hermes_out, *, mcp_url: str = DEFAULT_MCP_URL,
          mcp_transport: str = "auto", hook_bash: str | None = None) -> list[str]:
    """Generated files that differ from what the source would render now ([] = in sync)."""
    source_root, claude_out, hermes_out = Path(source_root), Path(claude_out), Path(hermes_out)
    claude, hermes, block = _expected(source_root, hermes_out, mcp_url, mcp_transport, SyncResult(), hook_bash)
    hermes["SOUL.md"] = _soul_text(hermes_out, block)
    drift: list[str] = []
    for label, out, files in (("claude", claude_out, claude), ("hermes", hermes_out, hermes)):
        for rel, data in sorted(files.items()):
            target = _inside(out, rel)
            if not target.is_file() or target.read_bytes() != data:
                drift.append(f"{label}:{rel}")
        drift += [f"{label}:{rel}" for rel in _prior(out)
                  if rel not in files and _inside(out, rel).is_file()]
    return drift


def source_digest(source_root) -> str:
    """Short hash of the rendered source; independent of cwd and of where it is checked out."""
    src = _load(Path(source_root))
    files = {**_claude_files(src),
             **_hermes_files(src, "/digest/out", "/digest/src", DEFAULT_MCP_URL, "auto", SyncResult(), "/digest/bash")}
    h = hashlib.sha256()
    for rel, data in sorted(files.items()):
        h.update(rel.encode() + b"\0" + data)
    return h.hexdigest()[:12]
